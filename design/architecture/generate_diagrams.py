def render(name, dot):
    path = os.path.join(HERE, f"{name}.dot")
    open(path, "w", encoding="utf-8").write(dot)
    sizes = []
    for fmt in ("svg", "png"):
        out = os.path.join(HERE, f"{name}.{fmt}")
        r = subprocess.run(["dot", f"-T{fmt}", path, "-o", out],
                           capture_output=True, text=True)
        if r.returncode:
            print(f"  ! graphviz failed on {name}.{fmt}: {r.stderr[:300]}", file=sys.stderr)
            return False
        sizes.append(f"{fmt} {os.path.getsize(out):,}b")
    print(f"  {name:24s} {' | '.join(sizes)}")
    return True


def main():
    os.makedirs(HERE, exist_ok=True)
    ok = render("system-architecture", architecture())
    ok &= render("data-flow", dataflow())
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
