#!/usr/bin/env python3
"""
D1 + D2 — generate the architecture and data-flow diagrams with Graphviz.

Same approach as generate_erd.py: the diagrams are generated, not hand-drawn,
so they can be re-rendered after a design change instead of quietly rotting.

These document the system AS BUILT (2026-07-29), not as originally imagined.
Node borders carry status:
    solid  = built and verified
    dashed = designed, not yet implemented

Writes: system-architecture.(dot|svg|png)
        data-flow.(dot|svg|png)

Usage:  python generate_diagrams.py
"""
import os
